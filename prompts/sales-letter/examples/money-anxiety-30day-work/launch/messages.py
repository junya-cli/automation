def _days(ns):
    return '・'.join(f'Day{d}' for d in sorted(set(ns)))


def type_cards():
    cards = []
    for n, t in TYPES.items():
        text = (f"{HEAD}\n{t['name']}のあなたへ\n\n▼ あなたの力\n{t['point']}\n\n▼ 30日で、特に大事な日\n{_days(t['days'])}\n\n"
                f"▼ 気をつけたいもれ口\n{'・'.join(t['leaks'])}\n\n▼ 最初の一歩\n{t['step']}\n\n▼ もしもの一文の例\n{t['ifthen']}\n\n▼ アオから\n{t['word']}")
        cards.append({'key': f'タイプ{n}', 'keys': [f'タイプ{n}'], 'title': t['name'], 'text': text})
    for (a, b), (mix, step, word) in PAIRS.items():
        ta, tb = TYPES[a], TYPES[b]
        leaks = list(dict.fromkeys(ta['leaks'] + tb['leaks']))
        text = (f"{HEAD}\n{ta['name']} × {tb['name']}のあなたへ\n\n▼ 2つが重なると\n{mix}\n\n▼ 30日で、特に大事な日\n{_days(ta['days'] + tb['days'])}\n\n"
                f"▼ 気をつけたいもれ口\n{'・'.join(leaks)}\n\n▼ 最初の一歩\n{step}\n\n▼ アオから\n{word}")
        cards.append({'key': f'タイプ{a}{b}', 'keys': [f'タイプ{a}{b}', f'タイプ{b}{a}'], 'title': f"{ta['name']} × {tb['name']}", 'text': text})
    return cards
