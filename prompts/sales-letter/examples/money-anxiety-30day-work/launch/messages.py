def _days(ns):
    return '・'.join(f'Day{d}' for d in sorted(set(ns)))


def _keys(*nums):
    """半角・全角の両方を登録する（キーワードは完全一致なので）"""
    ks = [f'タイプ{n}' for n in nums]
    return ks + [k.translate(ZEN) for k in ks]


