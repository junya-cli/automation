def to_html(blocks):
    out = []
    for kind, v in blocks:
        if kind == 'c':
            out.append(f'<p style="text-align:center">{v}</p>')
        elif kind in ('p', 'small'):
            out.append(f'<p>{v}</p>')
        elif kind in ('h2', 'h3'):
            out.append(f'<{kind}>{v}</{kind}>')
        elif kind in ('ul', 'ol'):
            out.append(f'<{kind}>' + ''.join(f'<li>{x}</li>' for x in v) + f'</{kind}>')
        elif kind == 'img':
            out.append(f'<p>【画像{v[0]}をここに挿入：{v[2]}（{v[1]}）】</p>')
        elif kind == 'todo':
            out.append(f'<p>【要確認：{v}】</p>')
        elif kind == 'hr':
            out.append('<hr>')
    return '\n'.join(out)


